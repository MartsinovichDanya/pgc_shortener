// Command reset generates Reset() methods for structs marked with "// generate:reset".
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	marker     = "generate:reset"
	outputName = "reset.gen.go"
)

type markedStruct struct {
	name string
	st   *ast.StructType
	recv string
}

func main() {
	root := flag.String("root", ".", "root for scanning")
	flag.Parse()

	seen := map[string]bool{}

	err := filepath.WalkDir(*root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			fmt.Fprintf(os.Stderr, "reset: %v\n", err)
			return nil
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if path != *root && (name == "vendor" || name == "testdata" || strings.HasPrefix(name, ".")) {
			return fs.SkipDir
		}
		if seen[path] {
			return nil
		}
		seen[path] = true
		if err := processDir(path); err != nil {
			fmt.Fprintf(os.Stderr, "reset: dir %s: %v\n", path, err)
		}
		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "reset: walk: %v\n", err)
		os.Exit(1)
	}
}

func processDir(dir string) error {
	// go/build корректно учитывает build-теги и не использует устаревший parser.ParseDir.
	bp, err := build.ImportDir(dir, 0)
	if err != nil {
		return nil // пустая директория, только _test-файлы и т.п. — пропускаем
	}

	fset := token.NewFileSet()
	var files []*ast.File
	for _, fn := range bp.GoFiles { // тестовые файлы и reset.gen.go сюда не входят
		f, err := parser.ParseFile(fset, filepath.Join(dir, fn), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil
	}
	pkgName := bp.Name

	var structs []*markedStruct
	known := map[string]bool{}
	for _, file := range files {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				if hasMarker(gd, ts) {
					structs = append(structs, &markedStruct{name: ts.Name.Name, st: st, recv: receiverName(ts.Name.Name)})
					known[ts.Name.Name] = true
				}
			}
		}
	}
	if len(structs) == 0 {
		return nil
	}
	sort.Slice(structs, func(i, j int) bool { return structs[i].name < structs[j].name })

	g := &generator{fset: fset, known: known, imports: map[string]bool{}}
	var sb strings.Builder
	for _, ms := range structs {
		g.genMethod(&sb, ms)
	}

	var head strings.Builder
	head.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	head.WriteString("package " + pkgName + "\n\n")
	for imp := range g.imports {
		fmt.Fprintf(&head, "import %q\n", imp)
	}
	if len(g.imports) > 0 {
		head.WriteString("\n")
	}
	head.WriteString(strings.TrimLeft(sb.String(), "\n"))

	formatted, err := format.Source([]byte(head.String()))
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	out := filepath.Join(dir, outputName)
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("reset: wrote %s (%d structs)\n", out, len(structs))
	return nil
}

func hasMarker(gd *ast.GenDecl, ts *ast.TypeSpec) bool {
	return commentHasMarker(gd.Doc) || commentHasMarker(ts.Doc) || commentHasMarker(ts.Comment)
}

func commentHasMarker(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}
	for _, c := range group.List {
		if strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(c.Text, "//"), "!")) == marker {
			return true
		}
	}
	return false
}

func receiverName(typeName string) string {
	vowels := "aeiouAEIOU"
	var sb strings.Builder
	for _, r := range typeName {
		if !strings.ContainsRune(vowels, r) {
			sb.WriteRune(toLower(r))
		}
	}
	name := sb.String()
	if name == "" || len(name) > 3 {
		name = strings.ToLower(typeName[:1])
	}
	return name
}

func toLower(r rune) rune {
	if r >= 'A' && r <= 'Z' {
		return r + 32
	}
	return r
}

type generator struct {
	fset    *token.FileSet
	known   map[string]bool // имена размеченных структур этого пакета
	imports map[string]bool // сторонние импорты, нужные для нулевых значений
}

// genMethod пишет в sb метод Reset() для одной структуры.
func (g *generator) genMethod(sb *strings.Builder, ms *markedStruct) {
	recv := ms.recv
	fmt.Fprintf(sb, "func (%s *%s) Reset() {\n", recv, ms.name)
	fmt.Fprintf(sb, "\tif %s == nil {\n\t\treturn\n\t}\n\n", recv)
	for _, field := range ms.st.Fields.List {
		for _, name := range field.Names {
			g.genField(sb, recv+"."+name.Name, field.Type, 1)
		}
		// безымянные (встроенные) поля пропускаем: у них нет имени для обращения
	}
	sb.WriteString("}\n\n")
}

func indent(lvl int) string { return strings.Repeat("\t", lvl) }

// genField генерирует операторы сброса поля selector с типом expr.
func (g *generator) genField(sb *strings.Builder, selector string, expr ast.Expr, lvl int) {
	switch t := unwrapParen(expr).(type) {
	case *ast.ArrayType:
		if t.Len == nil { // слайс []T — обрезаем по длине, не зануляем
			fmt.Fprintf(sb, "%s%s = %s[:0]\n", indent(lvl), selector, selector)
			return
		}
		// массив [N]T — рекурсивно обнуляем элементы
		fmt.Fprintf(sb, "%sfor idx := range %s {\n", indent(lvl), selector)
		g.genField(sb, selector+"[idx]", t.Elt, lvl+1)
		fmt.Fprintf(sb, "%s}\n", indent(lvl))
		return

	case *ast.MapType:
		fmt.Fprintf(sb, "%sclear(%s)\n", indent(lvl), selector)
		return

	case *ast.StarExpr: // указатель *T
		if inner, ok := unwrapParen(t.X).(*ast.Ident); ok && g.known[inner.Name] {
			// указатель на размеченную структуру этого пакета — вызываем её Reset()
			fmt.Fprintf(sb, "%sif %s != nil {\n", indent(lvl), selector)
			fmt.Fprintf(sb, "%s\t%s.Reset()\n", indent(lvl), selector)
			fmt.Fprintf(sb, "%s}\n", indent(lvl))
			return
		}
		// указатель на неизвестный именованный тип — сначала пробуем Reset() у pointed-to значения
		if inner, ok := unwrapParen(t.X).(*ast.Ident); ok && zeroLiteral(inner.Name) == "" && !isBuiltinNoReset(inner.Name) {
			fmt.Fprintf(sb, "%sif %s != nil {\n", indent(lvl), selector)
			g.genPointerToUnknown(sb, "*"+wrapIfNeeded(selector), exprText(g.fset, t.X), lvl+1)
			fmt.Fprintf(sb, "%s}\n", indent(lvl))
			return
		}
		fmt.Fprintf(sb, "%sif %s != nil {\n", indent(lvl), selector)
		g.genField(sb, "*"+wrapIfNeeded(selector), t.X, lvl+1)
		fmt.Fprintf(sb, "%s}\n", indent(lvl))
		return

	case *ast.StructType: // анонимная вложенная структура — сбрасываем поля
		for _, field := range t.Fields.List {
			for _, name := range field.Names {
				g.genField(sb, selector+"."+name.Name, field.Type, lvl)
			}
		}
		return

	case *ast.Ident:
		g.genIdent(sb, selector, t, lvl)
		return

	case *ast.SelectorExpr: // qualified type, например time.Duration
		g.addImport(t)
		g.assignZeroVar(sb, selector, exprText(g.fset, expr), lvl)
		return

	case *ast.InterfaceType, *ast.FuncType, *ast.ChanType:
		fmt.Fprintf(sb, "%s%s = nil\n", indent(lvl), selector)
		return

	default:
		g.assignZeroVar(sb, selector, exprText(g.fset, expr), lvl)
	}
}

func (g *generator) genIdent(sb *strings.Builder, selector string, id *ast.Ident, lvl int) {
	switch zeroLiteral(id.Name) {
	case "0", `""`, "false":
		fmt.Fprintf(sb, "%s%s = %s\n", indent(lvl), selector, zeroLiteral(id.Name))
		return
	}
	if g.known[id.Name] {
		// именованная размеченная структура этого пакета — у неё есть метод Reset()
		fmt.Fprintf(sb, "%s%s.Reset()\n", indent(lvl), selector)
		return
	}
	if isBuiltinNoReset(id.Name) {
		fmt.Fprintf(sb, "%s%s = nil\n", indent(lvl), selector)
		return
	}
	// неизвестный тип: если у него есть Reset() — вызываем, иначе обнуляем через var zero T
	fmt.Fprintf(sb, "%sif resetter, ok := any(%s).(interface{ Reset() }); ok && resetter != nil {\n", indent(lvl), selector)
	fmt.Fprintf(sb, "%s\tresetter.Reset()\n", indent(lvl))
	fmt.Fprintf(sb, "%s} else {\n", indent(lvl))
	fmt.Fprintf(sb, "%s\tvar zero %s\n", indent(lvl), id.Name)
	fmt.Fprintf(sb, "%s\t%s = zero\n", indent(lvl), selector)
	fmt.Fprintf(sb, "%s}\n", indent(lvl))
}

func (g *generator) genPointerToUnknown(sb *strings.Builder, deref, typeName string, lvl int) {
	fmt.Fprintf(sb, "%sif resetter, ok := any(%s).(interface{ Reset() }); ok && resetter != nil {\n", indent(lvl), deref)
	fmt.Fprintf(sb, "%s\tresetter.Reset()\n", indent(lvl))
	fmt.Fprintf(sb, "%s} else {\n", indent(lvl))
	fmt.Fprintf(sb, "%s\tvar zero %s\n", indent(lvl), typeName)
	fmt.Fprintf(sb, "%s\t%s = zero\n", indent(lvl), deref)
	fmt.Fprintf(sb, "%s}\n", indent(lvl))
}

func (g *generator) assignZeroVar(sb *strings.Builder, selector, typeName string, lvl int) {
	fmt.Fprintf(sb, "%svar zero %s\n", indent(lvl), typeName)
	fmt.Fprintf(sb, "%s%s = zero\n", indent(lvl), selector)
}

// wrapIfNeeded: составным селекторам нужны скобки — (rs.a.b)[:0], (*rs.p)[:0]
func wrapIfNeeded(selector string) string {
	if strings.Contains(selector, ".") || strings.Contains(selector, "[") {
		return "(" + selector + ")"
	}
	return selector
}

func unwrapParen(e ast.Expr) ast.Expr {
	for {
		p, ok := e.(*ast.ParenExpr)
		if !ok {
			return e
		}
		e = p.X
	}
}

func exprText(fset *token.FileSet, e ast.Expr) string {
	var b strings.Builder
	_ = printer.Fprint(&b, fset, e)
	return b.String()
}

func (g *generator) addImport(se *ast.SelectorExpr) {
	if id, ok := se.X.(*ast.Ident); ok {
		g.imports[id.Name] = true
	}
}

// zeroLiteral возвращает литерал нуля для базового типа по имени,
// либо "" если тип не является известным примитивом.
func zeroLiteral(name string) string {
	switch name {
	case "string":
		return `""`
	case "bool":
		return "false"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128",
		"byte", "rune":
		return "0"
	}
	return ""
}

func isBuiltinNoReset(name string) bool {
	switch name {
	case "error", "any", "comparable":
		return true
	}
	return false
}
