// Command reset generates Reset() methods for structs marked with "// generate:reset".
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"text/template"
)

const (
	marker     = "generate:reset"
	outputName = "reset.gen.go"
)

// ---- Модель операций ---------------------------------------------------

// Виды операций, которые умеет отрисовывать шаблон.
const (
	opAssignVar   = "assignVar"   // sel = value
	opZeroVar     = "zeroVar"     // var zero T; sel = zero
	opClear       = "clear"       // clear(sel)
	opSlice       = "slice"       // sel = sel[:0]
	opReset       = "reset"       // sel.Reset()
	opNil         = "nil"         // sel = nil
	opForRange    = "forRange"    // for idx := range sel { Body }
	opIfNotNil    = "ifNotNil"    // if sel != nil { Body }
	opResetOrZero = "resetOrZero" // if resetter, ok := any(sel).(...); ok { ... } else { var zero T; sel = zero }
)

// resetOp — одна операция сброса. Дерево из таких узлов
// полностью описывает тело сгенерированного метода.
type resetOp struct {
	Kind     string
	Selector string
	Value    string
	TypeName string
	Body     []*resetOp
}

type structInfo struct {
	Name string
	Recv string
	Body []*resetOp
}

type fileContext struct {
	Package string
	Imports []string
	Structs []structInfo
}

// ---- Шаблон ------------------------------------------------------------

// fileTemplate — единственное место, где описана «форма» выходного файла.
// Все отступы, склейки и регистр приведёт format.Source в самом конце.
const fileTemplate = `// Code generated by cmd/reset; DO NOT EDIT.

package {{.Package}}
{{if .Imports}}
import (
{{- range .Imports}}
{{.}}
{{- end}}
)
{{end}}
{{range .Structs}}func ({{.Recv}} *{{.Name}}) Reset() {
if {{.Recv}} == nil {
return
}
{{range .Body}}{{template "op" .}}{{end}}}
{{end}}
{{- define "op"}}{{if eq .Kind "assignVar"}}{{.Selector}} = {{.Value}}
{{else if eq .Kind "zeroVar"}}var zero {{.TypeName}}
{{.Selector}} = zero
{{else if eq .Kind "clear"}}clear({{.Selector}})
{{else if eq .Kind "slice"}}{{.Selector}} = {{.Selector}}[:0]
{{else if eq .Kind "reset"}}{{.Selector}}.Reset()
{{else if eq .Kind "nil"}}{{.Selector}} = nil
{{else if eq .Kind "forRange"}}for idx := range {{.Selector}} {
{{range .Body}}{{template "op" .}}{{end}}}
{{else if eq .Kind "ifNotNil"}}if {{.Selector}} != nil {
{{range .Body}}{{template "op" .}}{{end}}}
{{else if eq .Kind "resetOrZero"}}if resetter, ok := any({{.Selector}}).(interface{ Reset() }); ok && resetter != nil {
resetter.Reset()
} else {
var zero {{.TypeName}}
{{.Selector}} = zero
}
{{end}}{{end}}`

var tmpl = template.Must(template.New("file").Parse(fileTemplate))

// ---- Модель и обход ----------------------------------------------------

type markedStruct struct {
	name string
	st   *ast.StructType
	recv string
}

func Exit(code int) {
	os.Exit(code)
}

func main() {
	root := flag.String("root", ".", "root for scanning")
	flag.Parse()

	seen := map[string]bool{}

	err := filepath.WalkDir(*root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if path != *root && (name == "vendor" || name == "testdata" || strings.HasPrefix(name, ".")) {
			return fs.SkipDir
		}
		if seen[path] {
			return nil
		}
		seen[path] = true
		if err := processDir(path); err != nil {
			return fmt.Errorf("dir %s: %w", path, err)
		}
		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "reset: %v\n", err)
		Exit(1)
	}
}

func processDir(dir string) error {
	bp, err := build.ImportDir(dir, 0)
	if err != nil {
		return nil
	}

	fset := token.NewFileSet()
	var files []*ast.File
	for _, fn := range bp.GoFiles {
		f, err := parser.ParseFile(fset, filepath.Join(dir, fn), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil
	}
	pkgName := bp.Name

	var structs []*markedStruct
	known := map[string]bool{}
	for _, file := range files {
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				if hasMarker(gd, ts) {
					structs = append(structs, &markedStruct{name: ts.Name.Name, st: st, recv: receiverName(ts.Name.Name)})
					known[ts.Name.Name] = true
				}
			}
		}
	}
	if len(structs) == 0 {
		return nil
	}
	sort.Slice(structs, func(i, j int) bool { return structs[i].name < structs[j].name })

	g := &generator{fset: fset, known: known, imports: map[string]bool{}}
	infos := make([]structInfo, 0, len(structs))
	for _, ms := range structs {
		infos = append(infos, g.genStruct(ms))
	}

	imports := make([]string, 0, len(g.imports))
	for imp := range g.imports {
		imports = append(imports, strconv.Quote(imp))
	}
	sort.Strings(imports)

	ctx := fileContext{
		Package: pkgName,
		Imports: imports,
		Structs: infos,
	}

	var sb strings.Builder
	if err := tmpl.Execute(&sb, ctx); err != nil {
		return fmt.Errorf("template: %w", err)
	}
	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	out := filepath.Join(dir, outputName)
	if err := os.WriteFile(out, formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("reset: wrote %s (%d structs)\n", out, len(structs))
	return nil
}

func hasMarker(gd *ast.GenDecl, ts *ast.TypeSpec) bool {
	return commentHasMarker(gd.Doc) || commentHasMarker(ts.Doc) || commentHasMarker(ts.Comment)
}

func commentHasMarker(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}
	for _, c := range group.List {
		if strings.TrimSpace(strings.TrimPrefix(strings.TrimPrefix(c.Text, "//"), "!")) == marker {
			return true
		}
	}
	return false
}

func receiverName(typeName string) string {
	vowels := "aeiouAEIOU"
	var sb strings.Builder
	for _, r := range typeName {
		if !strings.ContainsRune(vowels, r) {
			sb.WriteRune(toLower(r))
		}
	}
	name := sb.String()
	if name == "" || len(name) > 3 {
		name = strings.ToLower(typeName[:1])
	}
	return name
}

func toLower(r rune) rune {
	if r >= 'A' && r <= 'Z' {
		return r + 32
	}
	return r
}

// ---- Генератор: только сбор данных ------------------------------------

type generator struct {
	fset    *token.FileSet
	known   map[string]bool
	imports map[string]bool
}

func (g *generator) genStruct(ms *markedStruct) structInfo {
	info := structInfo{Name: ms.name, Recv: ms.recv}
	for _, field := range ms.st.Fields.List {
		for _, name := range field.Names {
			info.Body = append(info.Body, g.genField(ms.recv+"."+name.Name, field.Type)...)
		}
	}
	return info
}

// genField возвращает последовательность операций сброса для выражения selector типа expr.
func (g *generator) genField(selector string, expr ast.Expr) []*resetOp {
	switch t := unwrapParen(expr).(type) {
	case *ast.ArrayType:
		if t.Len == nil {
			return []*resetOp{{Kind: opSlice, Selector: selector}}
		}
		return []*resetOp{{
			Kind:     opForRange,
			Selector: selector,
			Body:     g.genField(selector+"[idx]", t.Elt),
		}}

	case *ast.MapType:
		return []*resetOp{{Kind: opClear, Selector: selector}}

	case *ast.StarExpr:
		if inner, ok := unwrapParen(t.X).(*ast.Ident); ok && g.known[inner.Name] {
			return []*resetOp{{
				Kind:     opIfNotNil,
				Selector: selector,
				Body:     []*resetOp{{Kind: opReset, Selector: selector}},
			}}
		}
		if inner, ok := unwrapParen(t.X).(*ast.Ident); ok && zeroLiteral(inner.Name) == "" && !isBuiltinNoReset(inner.Name) {
			return []*resetOp{{
				Kind:     opIfNotNil,
				Selector: selector,
				Body: []*resetOp{{
					Kind:     opResetOrZero,
					Selector: "*" + wrapIfNeeded(selector),
					TypeName: exprText(g.fset, t.X),
				}},
			}}
		}
		return []*resetOp{{
			Kind:     opIfNotNil,
			Selector: selector,
			Body:     g.genField("*"+wrapIfNeeded(selector), t.X),
		}}

	case *ast.StructType:
		var ops []*resetOp
		for _, field := range t.Fields.List {
			for _, name := range field.Names {
				ops = append(ops, g.genField(selector+"."+name.Name, field.Type)...)
			}
		}
		return ops

	case *ast.Ident:
		return g.genIdent(selector, t)

	case *ast.SelectorExpr:
		g.addImport(t)
		return []*resetOp{{Kind: opZeroVar, Selector: selector, TypeName: exprText(g.fset, expr)}}

	case *ast.InterfaceType, *ast.FuncType, *ast.ChanType:
		return []*resetOp{{Kind: opNil, Selector: selector}}

	default:
		return []*resetOp{{Kind: opZeroVar, Selector: selector, TypeName: exprText(g.fset, expr)}}
	}
}

func (g *generator) genIdent(selector string, id *ast.Ident) []*resetOp {
	if lit := zeroLiteral(id.Name); lit != "" {
		return []*resetOp{{Kind: opAssignVar, Selector: selector, Value: lit}}
	}
	if g.known[id.Name] {
		return []*resetOp{{Kind: opReset, Selector: selector}}
	}
	if isBuiltinNoReset(id.Name) {
		return []*resetOp{{Kind: opNil, Selector: selector}}
	}
	return []*resetOp{{Kind: opResetOrZero, Selector: selector, TypeName: id.Name}}
}

func (g *generator) addImport(se *ast.SelectorExpr) {
	if id, ok := se.X.(*ast.Ident); ok {
		g.imports[id.Name] = true
	}
}

// ---- Вспомогательные функции ------------------------------------------

// wrapIfNeeded: составным селекторам нужны скобки — (rs.a.b)[:0], (*rs.p)[:0]
func wrapIfNeeded(selector string) string {
	if strings.Contains(selector, ".") || strings.Contains(selector, "[") {
		return "(" + selector + ")"
	}
	return selector
}

func unwrapParen(e ast.Expr) ast.Expr {
	for {
		p, ok := e.(*ast.ParenExpr)
		if !ok {
			return e
		}
		e = p.X
	}
}

func exprText(fset *token.FileSet, e ast.Expr) string {
	var b strings.Builder
	_ = printer.Fprint(&b, fset, e)
	return b.String()
}

func zeroLiteral(name string) string {
	switch name {
	case "string":
		return `""`
	case "bool":
		return "false"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"float32", "float64", "complex64", "complex128",
		"byte", "rune":
		return "0"
	}
	return ""
}

func isBuiltinNoReset(name string) bool {
	switch name {
	case "error", "any", "comparable":
		return true
	}
	return false
}
